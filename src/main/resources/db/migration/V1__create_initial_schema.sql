CREATE TYPE user_role AS ENUM ('ADMIN', 'CUSTOMER');
CREATE TYPE booking_status AS ENUM ('CONFIRMED', 'CANCELLED', 'WAITING');
CREATE TYPE event_status AS ENUM ('OPEN_FOR_BOOKING', 'FINISHED');

CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role user_role DEFAULT 'CUSTOMER',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE events (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    event_date TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL,
    location VARCHAR(255) NOT NULL,
    status event_status NOT NULL DEFAULT 'DRAFT',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bookings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    status booking_status DEFAULT 'CONFIRMED',
    confirmation_code UUID NOT NULL UNIQUE,
    cancelled_at TIMESTAMPTZ,
    event_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_booking FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_user_booking FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_user_event UNIQUE (event_id, user_id)
);

CREATE INDEX idx_user_email ON users(email);
CREATE INDEX idx_booking_confirmation ON bookings(confirmation_code);